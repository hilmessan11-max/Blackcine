// Current language
let currentLang = localStorage.getItem('blackcine_lang') || 'fr';

/**
 * Get translation for a key
 */
function t(key) {
  return translations[currentLang]?.[key] || translations['fr']?.[key] || key;
}

/**
 * Translate all elements with data-key attribute
 */
function translate(lang) {
  currentLang = lang;
  localStorage.setItem('blackcine_lang', lang);
  
  document.querySelectorAll('[data-key]').forEach(el => {
    const key = el.getAttribute('data-key');
    const translation = translations[lang]?.[key];
    if (translation) {
      el.innerHTML = translation;
    }
  });

  // Translate placeholders
  document.querySelectorAll('[data-key-placeholder]').forEach(el => {
    const key = el.getAttribute('data-key-placeholder');
    const translation = translations[lang]?.[key];
    if (translation) {
      el.placeholder = translation;
    }
  });

  // Translate alt attributes
  document.querySelectorAll('[data-key-alt]').forEach(el => {
    const key = el.getAttribute('data-key-alt');
    const translation = translations[lang]?.[key];
    if (translation) {
      el.alt = translation;
    }
  });

  // Update lang toggle button
  const langBtn = document.getElementById('lang-toggle');
  if (langBtn) {
    langBtn.innerHTML = `${lang === 'fr' ? 'Français' : 'English'}<i class="fa-solid fa-chevron-down"></i>`;
  }

  // Update HTML lang attribute
  document.documentElement.lang = lang;
}

/**
 * Toggle between FR and EN
 */
function toggleLang() {
  const newLang = currentLang === 'fr' ? 'en' : 'fr';
  translate(newLang);
}

/**
 * Initialize i18n on page load
 */
function initI18n() {
  translate(currentLang);
  
  const langBtn = document.getElementById('lang-toggle');
  if (langBtn) {
    langBtn.addEventListener('click', toggleLang);
  }
}

// Auto-initialize when DOM is ready
if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', initI18n);
} else {
  initI18n();
}
